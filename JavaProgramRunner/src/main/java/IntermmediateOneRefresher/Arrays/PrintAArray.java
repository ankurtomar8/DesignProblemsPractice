package IntermmediateOneRefresher.Arrays;

public class PrintAArray {

    public static void main(String[] args) {
        int[] array = {10, 20, 30, 40, 1, 7, 5, 9, 6, 3, 74};

        for (int i = 0; i < array.length; i++) {
            System.out.print(" "+array[i]);
        }
        System.out.println();
    }
}
